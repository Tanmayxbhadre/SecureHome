// Cross-language test vectors for the Android port.
//   node scripts/vectors.mjs            write ../fixtures/crypto-vectors.json (JS → Kotlin)
//   node scripts/vectors.mjs --check F  verify a file the Kotlin tests wrote (Kotlin → JS)
import { readFile, writeFile } from "node:fs/promises";
import { isDeepStrictEqual } from "node:util";
import * as C from "../public/js/crypto.js";

const subtle = globalThis.crypto.subtle;
const HID = "H".repeat(22);
const FROM = "F".repeat(22);
const TO = "T".repeat(22);

async function privD(key) {
  return (await subtle.exportKey("jwk", key)).d;
}

async function write() {
  const recipient = await C.generateDeviceKeys(true);
  const founder = await C.generateDeviceKeys(true);
  const laptop = await C.generateDeviceKeys(true);
  const payload = { v: 1, kind: "otp", code: "845210", sender: "HDFCBK", body: "₹ unicode ✓ \"quoted\" </script>", receivedAt: 1795000000000 };
  const aad = C.itemAad(HID, FROM, TO);
  const { env, sas } = await C.seal({ recipientEncPub: recipient.enc.publicKey, signerSigPriv: founder.sig.privateKey, info: C.INFO.item, aad, payload });

  const founderId = C.randomId();
  const laptopId = C.randomId();
  const pub = async (k) => C.exportPub(k.publicKey);
  const founderEntry = await C.signEntry(
    { v: 1, id: founderId, name: "My phone", kind: "phone", encPub: await pub(founder.enc), sigPub: await pub(founder.sig), addedBy: founderId, addedAt: 1 },
    founder.sig.privateKey,
  );
  const laptopEntry = await C.signEntry(
    { v: 1, id: laptopId, name: "Work laptop", kind: "laptop", encPub: await pub(laptop.enc), sigPub: await pub(laptop.sig), addedBy: founderId, addedAt: 2 },
    founder.sig.privateKey,
  );
  // An entry the relay might inject: self-consistent but signed by a key outside the household.
  const rogue = await C.generateDeviceKeys(true);
  const rogueId = C.randomId();
  const rogueEntry = await C.signEntry(
    { v: 1, id: rogueId, name: "Rogue", kind: "laptop", encPub: await pub(rogue.enc), sigPub: await pub(rogue.sig), addedBy: founderId, addedAt: 3 },
    rogue.sig.privateKey,
  );
  // Signed by the laptop: valid signature, but laptops may not add devices.
  const viaLaptopId = C.randomId();
  const viaLaptop = await C.signEntry(
    { v: 1, id: viaLaptopId, name: "Via laptop", kind: "phone", encPub: await pub(rogue.enc), sigPub: await pub(rogue.sig), addedBy: laptopId, addedAt: 4 },
    laptop.sig.privateKey,
  );

  const out = {
    note: "Generated by relay/scripts/vectors.mjs. Private keys are throwaway test keys.",
    recipient: { encPub: await pub(recipient.enc), encPrivD: await privD(recipient.enc.privateKey) },
    envelope: { info: C.INFO.item, aad, env, sas, payload, signerSigPub: await pub(founder.sig) },
    roster: {
      founderSigPub: await pub(founder.sig),
      entries: [founderEntry, rogueEntry, laptopEntry, viaLaptop],
      expectIds: [founderId, laptopId],
    },
    sha256: { input: "abc", hex: await C.sha256Hex("abc") },
  };
  await writeFile(new URL("../../fixtures/crypto-vectors.json", import.meta.url), JSON.stringify(out, null, 2) + "\n");
  console.log("wrote fixtures/crypto-vectors.json");
}

async function check(file) {
  const v = JSON.parse(await readFile(file, "utf8"));
  const fx = JSON.parse(await readFile(new URL("../../fixtures/crypto-vectors.json", import.meta.url), "utf8"));
  const recipientPriv = await subtle.importKey(
    "jwk",
    { kty: "EC", crv: "P-256", d: fx.recipient.encPrivD, ...xy(fx.recipient.encPub) },
    { name: "ECDH", namedCurve: "P-256" },
    false,
    ["deriveBits"],
  );
  const signer = await C.importSigPub(v.signerSigPub);
  if (!(await C.verifyEnvelope(v.env, v.aad, signer))) throw new Error("Kotlin envelope signature did not verify");
  const { payload, sas } = await C.openEnvelope(v.env, v.aad, recipientPriv, v.info);
  if (!isDeepStrictEqual(payload, v.payload)) throw new Error(`payload mismatch: ${JSON.stringify(payload)}`);
  if (sas !== v.sas) throw new Error(`SAS mismatch: ${sas} vs ${v.sas}`);
  const roster = await C.verifyRoster(v.roster.entries, v.roster.founderSigPub);
  if ([...roster.keys()].join() !== v.roster.expectIds.join()) throw new Error("Kotlin roster did not verify");
  console.log("Kotlin vectors verify in JavaScript: envelope, SAS, roster ✓");
}

function xy(b64u) {
  const raw = C.b64uDecode(b64u);
  return { x: C.b64uEncode(raw.slice(1, 33)), y: C.b64uEncode(raw.slice(33, 65)) };
}

const i = process.argv.indexOf("--check");
await (i > 0 ? check(process.argv[i + 1]) : write());
